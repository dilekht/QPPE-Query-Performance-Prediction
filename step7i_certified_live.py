#!/usr/bin/env python3
"""
QPPE Rebuild - Step 7i: Certified Live Validation (Both Benchmarks)
====================================================================
The sample-size floor (7f-7h) dictates the design: use ALL corpus
queries for policy-level cross-conformal calibration, validate LIVE on
FRESH queries.

  Part A  Calibration per benchmark: 5-fold OOF policy outcomes over
          all queries (query units); t* = largest grid threshold whose
          CP bound on P(severe | steered) passes (alpha, delta).
          Cross-conformal approximation - the live run is its test.
  Part B  Fresh queries: TPC-H uses the 17 v100+ variants from Step 6.
          JOB variants are GENERATED by perturbing literal constants
          (years +1, rating thresholds) in the official queries, then
          EXPLAIN-validated; ~15 kept.
  Part C  Live loop on fresh queries: 12 EXPLAINs -> gate -> execute
          chosen + default (warm-up + 3 runs), materially-severe rate
          vs alpha, speedup with overhead included.

Requires step6_live_loop.py, step3c_expand_corpus.py,
step7c_job_analysis.py, and the job_queries/ folder.

Usage:
    py step7i_certified_live.py --user postgres --password 12345
Expected duration: 40-70 minutes (live execution on both benchmarks).
"""

import argparse
import glob
import importlib.util
import json
import os
import pathlib
import re
import time

import numpy as np
import pandas as pd

RATIO_EPS = 1e-9


def load_module(name, filename):
    spec = importlib.util.spec_from_file_location(
        name, str(pathlib.Path(__file__).parent / filename))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def new_model():
    from sklearn.ensemble import GradientBoostingClassifier
    return GradientBoostingClassifier(
        n_estimators=250, max_depth=3, learning_rate=0.05,
        subsample=0.8, min_samples_leaf=8, random_state=42)


def severe_label(cand, theta_sev, floor_ms):
    slow = cand["median_ms"] / (cand["def_median_ms"] + RATIO_EPS)
    added = cand["median_ms"] - cand["def_median_ms"]
    return (((slow > theta_sev) & (added > floor_ms)) |
            cand["censored"]).astype(int)


def policy_outcomes(df, t, tau_win, theta_sev, floor_ms):
    outcomes = []
    for qid, g in df.groupby("query_id"):
        d_ms = g["def_median_ms"].iloc[0]
        cert = g[(g["p_severe"] < t) & (g["p_win"] > tau_win)]
        if cert.empty:
            outcomes.append((False, False))
            continue
        top = cert.loc[cert["p_win"].idxmax()]
        c_ms = top["median_ms"]
        slow = c_ms / d_ms if d_ms > 0 else 1.0
        severe = (slow > theta_sev and (c_ms - d_ms) > floor_ms) or \
                 bool(top["censored"])
        outcomes.append((True, severe))
    return outcomes


def calibrate(cand, feats, args, s6, label):
    """Cross-conformal policy-level calibration over all queries."""
    cand = cand.reset_index(drop=True).copy()
    rng = np.random.default_rng(11)
    qids = rng.permutation(cand["query_id"].unique())
    folds = np.array_split(qids, 5)
    cand["p_severe"] = np.nan
    cand["p_win"] = np.nan
    for fold_q in folds:
        te = cand.query_id.isin(set(fold_q))
        ms = new_model()
        ms.fit(cand.loc[~te, feats], cand.loc[~te, "is_severe"])
        cand.loc[te, "p_severe"] = ms.predict_proba(cand.loc[te, feats])[:, 1]
        mw = new_model()
        mw.fit(cand.loc[~te, feats], cand.loc[~te, "is_win"])
        cand.loc[te, "p_win"] = mw.predict_proba(cand.loc[te, feats])[:, 1]

    grid = np.unique(np.quantile(cand["p_severe"].values,
                                 np.linspace(0.05, 0.95, 30)))
    t_star, best_n, best_k = 0.0, 0, 0
    for t in grid:
        out = policy_outcomes(cand, t, args.tau_win,
                              args.theta_sev, args.floor_ms)
        n = sum(1 for s, _ in out if s)
        k = sum(1 for s, sv in out if s and sv)
        if n > 0 and s6.clopper_pearson_upper(k, n, args.delta) <= args.alpha:
            t_star, best_n, best_k = float(t), n, k
    print(f"  [{label}] cross-conformal t* = {t_star:.3f} "
          f"(calibration: {best_n} steered queries, {best_k} severe, "
          f"CP bound passes at alpha={args.alpha})")

    heads_s = new_model()
    heads_s.fit(cand[feats], cand["is_severe"])
    heads_w = new_model()
    heads_w.fit(cand[feats], cand["is_win"])
    return t_star, heads_s, heads_w


def make_fresh_job_queries(qdir, bcur, max_n=15):
    """Perturb literal constants in official JOB queries; keep those
    that EXPLAIN cleanly. Returns list of (name, sql)."""
    files = sorted(glob.glob(os.path.join(qdir, "**", "*.sql"),
                             recursive=True))
    fresh = []
    seen_families = set()
    for path in files:
        base = os.path.basename(path)
        if not re.fullmatch(r"\d+[a-z]\.sql", base):
            continue
        family = re.match(r"(\d+)", base).group(1)
        if family in seen_families:
            continue
        with open(path, "r", encoding="utf-8") as f:
            sql = f.read().strip().rstrip(";")
        orig = sql
        # perturb years (+1) and rating thresholds
        sql = re.sub(r"\b(19[5-9]\d|20[0-1]\d)\b",
                     lambda m: str(int(m.group(1)) + 1), sql)
        sql = sql.replace("> 8.0", "> 7.5").replace("> 9.0", "> 8.5")
        if sql == orig:
            continue  # nothing perturbed -> not fresh
        try:
            bcur.execute(f"EXPLAIN (FORMAT JSON) {sql}")
            bcur.fetchone()
        except Exception:
            try:
                bcur.execute("ROLLBACK;")
            except Exception:
                pass
            continue
        fresh.append((f"{base[:-4]}-fresh", sql))
        seen_families.add(family)
        if len(fresh) >= max_n:
            break
    return fresh


def live_loop(label, fresh_queries, t_star, heads_s, heads_w, feats,
              bcur, s6, args):
    print(f"\nLIVE - {label} ({len(fresh_queries)} fresh queries, "
          f"t* = {t_star:.3f})")
    print(f"{'query':<14}{'decision':<22}{'default ms':>11}"
          f"{'chosen ms':>10}{'ovh ms':>8}{'result':>12}")
    print("-" * 79)
    results = []
    for qname, sql in fresh_queries:
        t0 = time.perf_counter()
        plans = {}
        failed = False
        for hs_name, gucs in s6.HINT_SETS.items():
            bcur.execute("BEGIN;")
            try:
                for guc, val in gucs.items():
                    bcur.execute(f"SET LOCAL {guc} = {val};")
                bcur.execute(f"EXPLAIN (FORMAT JSON) {sql}")
                plan = bcur.fetchone()[0]
                if isinstance(plan, str):
                    plan = json.loads(plan)
                plans[hs_name] = plan[0]["Plan"]
            except Exception:
                failed = True
            finally:
                try:
                    bcur.execute("ROLLBACK;")
                except Exception:
                    pass
        if failed or "default" not in plans:
            print(f"{qname:<14}{'planning failed - skipped':<22}")
            continue
        gen_ms = (time.perf_counter() - t0) * 1000

        t0 = time.perf_counter()
        def_flat = s6.flat_features(plans["default"])
        def_node = s6.node_features(plans["default"])
        rows, names = [], []
        for hs_name, root in plans.items():
            if hs_name == "default":
                continue
            rows.append(s6.build_feature_row(
                s6.flat_features(root), s6.node_features(root),
                def_flat, def_node, hs_name))
            names.append(hs_name)
        F = pd.DataFrame(rows)[feats]
        p_sev = heads_s.predict_proba(F)[:, 1]
        p_win = heads_w.predict_proba(F)[:, 1]
        inf_ms = (time.perf_counter() - t0) * 1000

        cert = [(names[i], p_sev[i], p_win[i]) for i in range(len(names))
                if p_sev[i] < t_star and p_win[i] > args.tau_win]
        if cert:
            chosen_hs = max(cert, key=lambda x: x[2])[0]
            decision = f"steer:{chosen_hs}"
        else:
            chosen_hs = "default"
            decision = "keep default"

        d_ms, _ = s6.measure(bcur, sql, {}, 180000)
        timeout = min(max(3 * d_ms, 10000), 180000)
        if chosen_hs == "default":
            c_ms = d_ms
        else:
            c_ms, _ = s6.measure(bcur, sql, s6.HINT_SETS[chosen_hs], timeout)

        slow = c_ms / d_ms if d_ms > 0 else 1.0
        severe = (chosen_hs != "default" and slow > args.theta_sev
                  and (c_ms - d_ms) > args.floor_ms)
        if chosen_hs == "default":
            result = "-"
        elif severe:
            result = "SEVERE"
        elif slow > 1.2:
            result = "mild regr"
        elif c_ms < d_ms:
            result = f"won {d_ms/c_ms:.1f}x"
        else:
            result = "~neutral"
        results.append(dict(default_ms=d_ms, chosen_ms=c_ms,
                            gen_ms=gen_ms, inf_ms=inf_ms,
                            steered=chosen_hs != "default", severe=severe))
        print(f"{qname:<14}{decision:<22}{d_ms:>11.0f}{c_ms:>10.0f}"
              f"{gen_ms + inf_ms:>8.1f}{result:>12}")

    R = pd.DataFrame(results)
    if R.empty:
        print("No queries executed.")
        return
    tot_def = R.default_ms.sum()
    tot_pol = R.chosen_ms.sum() + R.gen_ms.sum() + R.inf_ms.sum()
    n_st, n_sv = int(R.steered.sum()), int(R.severe.sum())
    print("-" * 79)
    print(f"  {label}: steered {n_st}/{len(R)} | SEVERE {n_sv} "
          f"(rate {n_sv/max(n_st,1):.2f} vs alpha {args.alpha}) | "
          f"workload {tot_def/1000:.1f}s -> {tot_pol/1000:.1f}s "
          f"({(tot_def-tot_pol)/tot_def*100:+.1f}%, overhead incl.) | "
          f"overhead {R.gen_ms.mean()+R.inf_ms.mean():.1f} ms avg")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--user", default="postgres")
    parser.add_argument("--password", default="postgres")
    parser.add_argument("--host", default="localhost")
    parser.add_argument("--port", type=int, default=5432)
    parser.add_argument("--log-db", default="qppe")
    parser.add_argument("--queries-dir", default="job_queries")
    parser.add_argument("--theta-sev", type=float, default=2.0)
    parser.add_argument("--floor-ms", type=float, default=1000.0)
    parser.add_argument("--theta-win", type=float, default=0.9)
    parser.add_argument("--alpha", type=float, default=0.10)
    parser.add_argument("--delta", type=float, default=0.10)
    parser.add_argument("--tau-win", type=float, default=0.5)
    args = parser.parse_args()

    import psycopg2
    s6 = load_module("s6", "step6_live_loop.py")
    s7c = load_module("s7c", "step7c_job_analysis.py")

    print("QPPE Step 7i - Certified Live Validation")
    print("=" * 72)
    print(f"Certified event: slowdown > {args.theta_sev}x AND added > "
          f"{args.floor_ms:.0f} ms (or timeout) | alpha={args.alpha}, "
          f"delta={args.delta}")

    # ---------------- Part A: calibration ----------------
    print("\nPART A - cross-conformal calibration over full corpora")
    bench_data = {}
    for label, bname, vmax in [("TPC-H", "tpch_sf1", 100),
                               ("JOB", "imdb", None)]:
        cand = s7c.load_benchmark(args, s6, bname, variant_max=vmax)
        cand = cand.reset_index(drop=True)
        cand["slowdown"] = cand["median_ms"] / (cand["def_median_ms"] + RATIO_EPS)
        cand["is_severe"] = severe_label(cand, args.theta_sev, args.floor_ms)
        cand["is_win"] = ((cand["slowdown"] < args.theta_win) &
                          ~cand["censored"]).astype(int)
        feats = [c for c in cand.columns
                 if c not in ("template", "query_id", "median_ms",
                              "def_median_ms", "censored", "slowdown",
                              "is_severe", "is_win")]
        t_star, hs_, hw_ = calibrate(cand, feats, args, s6, label)
        bench_data[label] = (t_star, hs_, hw_, feats)

    # ---------------- Part B+C: live runs ----------------
    # TPC-H
    s3c = load_module("s3c", "step3c_expand_corpus.py")
    conn = psycopg2.connect(dbname="tpch_sf1", user=args.user,
                            password=args.password, host=args.host,
                            port=args.port)
    conn.autocommit = True
    bcur = conn.cursor()
    tpch_fresh = [(f"{t}v{v}", s3c.TEMPLATES[t].format(**p))
                  for t, v, p in s6.FRESH]
    t_star, hs_, hw_, feats = bench_data["TPC-H"]
    live_loop("TPC-H fresh", tpch_fresh, t_star, hs_, hw_, feats,
              bcur, s6, args)
    bcur.close(); conn.close()

    # JOB
    conn = psycopg2.connect(dbname="imdb", user=args.user,
                            password=args.password, host=args.host,
                            port=args.port)
    conn.autocommit = True
    bcur = conn.cursor()
    job_fresh = make_fresh_job_queries(args.queries_dir, bcur)
    print(f"\nGenerated {len(job_fresh)} fresh JOB variants: "
          f"{', '.join(n for n, _ in job_fresh)}")
    t_star, hs_, hw_, feats = bench_data["JOB"]
    live_loop("JOB fresh", job_fresh, t_star, hs_, hw_, feats,
              bcur, s6, args)
    bcur.close(); conn.close()

    print("\nDone. Paste the full output back.")


if __name__ == "__main__":
    main()
